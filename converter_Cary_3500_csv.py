#!/usr/bin/env python3
"""
Cary 3500 UV-Vis melting CSV converter

Input CSV structure (the output csv file generated by the control software):
- Row 1: sample_name, , sample_name2, , sample_name3, sample_name4, ...
- Row 2: Temperature (C), Abs, Temperature (C), Abs, ...
- Rows 3+: temperature, absorbance, temperature, absorbance, ...

Columns come in PAIRS (Temperature, Abs). For each sample, there are `stages`
pairs in a row (Stage 1 pair, Stage 2 pair, ...), then the next sample, etc.

This script:
1) Prompts to select CSV.
2) Prompts for number of stages and a comma-separated list of scan rates
   (e.g., -2, 2, -1, 1), and whether to apply temperature correction (Y/N).
3) Extracts each sample's curve for each stage, sorts temperature ascending.
4) If correction enabled: applies linear temperature correction for rates
   in {±1, ±2, ±3, ±4} °C/min per provided formulas.
5) Groups curves by scan rate; writes one CSV per unique scan rate with:
   - First column: Temperature (corrected if applicable)
   - Subsequent columns: one per curve, named "<sample>_stage<k>"

Notes:
- Temperatures across curves in a group are outer-joined (no interpolation).
- If a provided stage rate is not exactly ±1/2/3/4 and correction is enabled,
  that stage will be left uncorrected (with a warning).
"""

import os
import sys
import math
import tkinter as tk
from tkinter import filedialog
from typing import Dict, List, Tuple

import numpy as np
import pandas as pd


# I/O helper -----------------------------------------------------------
def choose_csv_file() -> str:
    root = tk.Tk()
    root.withdraw()
    path = filedialog.askopenfilename(
        title="Select Cary 3500 output file (.CSV)",
        filetypes=[("CSV files", "*.csv"), ("All files", "*.*")]
    )
    if not path:
        print("No file selected. Exiting.")
        sys.exit(1)
    return path

# Input of experimental settings ---------------------------------------
def prompt_experiment() -> Tuple[int, List[float], bool]:
    def get_int(prompt: str, lo: int, hi: int) -> int:
        while True:
            try:
                v = int(input(prompt).strip())
                if lo <= v <= hi:
                    return v
            except Exception:
                pass
            print(f"Please enter an integer between {lo} and {hi}.")

    stages = get_int("Number of stages (1–8): ", 1, 8)

    while True:
        # Rates can be integers or float. They usually range from 0.1 to 5 °C/min
        raw = input(
            f""""Enter {stages} scan rates (°C/min) in order, comma-separated 
            (e.g., -2, 2, -1, 1): """
        ).strip()
        try:
            rates = [float(x.strip()) for x in raw.split(",")]
        except Exception:
            print("Could not parse numbers. Try again.")
            continue
        if len(rates) != stages:
            print(f"Expected exactly {stages} values.")
            continue
        # Reject values outside 0.1 5- 5.
        if not all(0.1 <= abs(r) <= 5.0 for r in rates):
            print("Each rate must be between 0.1 and 5.0 °C/min.")
            continue
        # Reject 0.
        if any(abs(r) < 1e-12 for r in rates):
            print("Rates cannot be zero.")
            continue
        break

    corr_raw = input("Apply temperature correction? (Y/N): ").strip().lower()
    correction = corr_raw.startswith("y")

    if correction and not all(abs(round(r)) in {1, 2, 3, 4} for r in rates):
        print(
            "Note: Temperature correction only defined for rate in {1,2,3,4} °C/min.\n"
            "Stages with other rates will be left uncorrected."
        )

    return stages, rates, correction


# Data parsing & processing --------------------------------------------
def read_cary_csv(path: str) -> pd.DataFrame:
    # We keep all cells; headers are on first two rows.
    df = pd.read_csv(path, header=None, dtype=str)
    return df


def temp_correction(temp_arr: np.ndarray, scan_rate: float) -> np.ndarray:
    """
    Apply linear T correction for scan rates ±1/2/3/4 (exact integer match).
    Returns corrected temperatures. If no matching rate, returns original.
    """
    # Only apply correction for supported rates.
    scan_rate = int(scan_rate)
    if abs(scan_rate) not in {1, 2, 3, 4}:
        return temp_arr  # not a supported rate -> no correction

    # Map of (sign*rate) -> (a, b) for a*T + b
    coeffs: Dict[int, Tuple[float, float]] = {
        -4: (0.9669,  6.7276),
         4: (0.9690, -3.8390),
        -3: (0.9600,  5.5491),
         3: (0.9718, -2.9842),
        -2: (0.9572,  4.2738),
         2: (0.9780, -2.0099),
        -1: (0.9737,  2.3471),
         1: (0.9863, -0.8480),
    }
    a, b = coeffs[scan_rate if scan_rate >= 0 else -abs(scan_rate)]
    return a * temp_arr + b


def extract_curves(df: pd.DataFrame,
                   stages: int,
                   stage_rates: List[float],
                   apply_correction: bool
                   ) -> Dict[float, List[pd.DataFrame]]:
    """
    Parse the Cary CSV into per-stage, per-sample curves and group by scan rate.

    Returns:
      group_by_rate: dict[rate] -> list of DataFrames with columns:
          ['Temperature', '<sample>_stage<k>']
    """
    if df.shape[0] < 3:
        raise ValueError("CSV must have at least 3 rows (names, headers, data).")

    # First two rows are headers
    name_row = df.iloc[0, :].tolist()
    # header_row = df.iloc[1, :]  # not strictly needed, but kept for clarity

    n_cols = df.shape[1]
    if n_cols % 2 != 0:
        raise ValueError("Expected an even number of columns (pairs of Temp/Abs).")

    total_pairs = n_cols // 2
    if total_pairs % stages != 0:
        raise ValueError(
            f"""Columns imply {total_pairs} curve pairs; not divisible by stages={stages}.\n
            Make sure the CSV pairs are arranged as: for each SAMPLE -> 
            all STAGES, then next sample."""
        )

    num_samples = total_pairs // stages
    # Data rows start at row index 2
    data_only = df.iloc[2:, :].copy()

    # Convert all numeric-like cells to float where possible
    # Convert per column.
    group_by_rate: Dict[float, List[pd.DataFrame]] = {}

    def clean_sample_name(raw_name: str, fallback_idx: int) -> str:
        """

        :param raw_name: the name taken from the first row.
        :param fallback_idx: index of the name cell, in case an invalid name is found.
        :return: new_name that is stripped off from the wavelength and temp range.
        """
        new_name = (raw_name or "").strip()
        new_name = new_name.split("_260.00nm")[0]
        if not new_name:
            new_name = f"sample{fallback_idx}"
        return new_name

    # Go sample by sample, stage by stage, in the assumed layout:
    # For sample s, stage k:
    #   start_col = (s*stages + k) * 2  (Temp col), Abs at start_col+1
    for s in range(num_samples):
        # Resolve sample name from the FIRST pair of this sample (best-effort)
        first_pair_col = (s * stages) * 2
        sample_name = clean_sample_name(str(name_row[first_pair_col]), s + 1)

        for k in range(stages):
            rate = stage_rates[k]
            temp_col = (s * stages + k) * 2
            abs_col = temp_col + 1

            # Pull numeric arrays; coerce errors to NaN then drop
            temp_vals = pd.to_numeric(data_only.iloc[:, temp_col], errors="coerce")
            abs_vals = pd.to_numeric(data_only.iloc[:, abs_col], errors="coerce")

            # Drop rows where Temperature is NaN; keep aligned Abs
            mask = temp_vals.notna()
            temp_vals = temp_vals[mask].to_numpy()
            abs_vals = abs_vals[mask].to_numpy()

            if temp_vals.size == 0:
                # Empty curve; skip
                continue

            # Sort ascending by temperature
            order = np.argsort(temp_vals)
            temp_vals = temp_vals[order]
            abs_vals = abs_vals[order]

            # Optional temperature correction
            if apply_correction:
                corrected = temp_correction(temp_vals, rate)
                if corrected is temp_vals:
                    # No correction applied for this rate
                    pass
                temp_vals = corrected

                # Re-sort in case linear transform changed order (it shouldn't invert, but be safe)
                o2 = np.argsort(temp_vals)
                temp_vals = temp_vals[o2]
                abs_vals = abs_vals[o2]

            # Make a tiny 2-col dataframe for this curve
            col_name = f"{sample_name}"
            curve_df = pd.DataFrame(
                {"Temperature": temp_vals, col_name: abs_vals}
            )

            # Append into group for this scan rate
            group_by_rate.setdefault(rate, []).append(curve_df)

    return group_by_rate


def merge_group_to_wide(curves: List[pd.DataFrame]) -> pd.DataFrame:
    """
    Outer-join a list of ['Temperature', series] DataFrames on 'Temperature'.
    Ensures a single Temperature column, ascending order.
    """
    if not curves:
        return pd.DataFrame(columns=["Temperature"])
    out = curves[0]
    for df in curves[1:]:
        out = pd.merge(out, df, on="Temperature", how="outer")
    out = out.sort_values("Temperature").reset_index(drop=True)
    return out


def rate_label(rate: float) -> str:
    direction = "cooling" if rate < 0 else "heating"
    # Represent absolute rate nicely (avoid trailing .0)
    r_abs = abs(rate)
    r_txt = f"{r_abs:g}"  # e.g., 2, 2.5, 0.5
    return f"{direction}_{r_txt}Cmin"


def write_outputs(
    basepath: str,
    grouped: Dict[float, List[pd.DataFrame]],
    corrected: bool
) -> List[str]:
    base, _ = os.path.splitext(basepath)
    written = []
    for rate, dfs in grouped.items():
        wide = merge_group_to_wide(dfs)
        # Move Temperature to first column explicitly (already first, but ensure)
        cols = ["Temperature"] + [c for c in wide.columns if c != "Temperature"]
        wide = wide[cols]

        suffix = rate_label(rate)
        if corrected:
            suffix += "_corrected"
        out_path = f"{base}_{suffix}.csv"
        wide.to_csv(out_path, index=False)
        written.append(out_path)
    return written


# Main -----------------------------------------------------------------
def main():
    print("\n=== Cary 3500 UV-Vis melting CSV converter ===\n")
    csv_path = choose_csv_file()
    stages, rates, correction = prompt_experiment()

    df = read_cary_csv(csv_path)
    grouped = extract_curves(df, stages=stages, stage_rates=rates, apply_correction=correction)
    if not grouped:
        print("No curves extracted. Nothing to write.")
        return

    outputs = write_outputs(csv_path, grouped, corrected=correction)

    print("\nWrote the following files:")
    for p in outputs:
        print("  -", os.path.basename(p))
    print("\nDone.")


if __name__ == "__main__":
    main()
